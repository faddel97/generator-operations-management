/* eslint-disable @typescript-eslint/no-require-imports */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

async function main() {
  const out = path.resolve("output", "tracking-review");
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe" });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } });
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("response", (response) => { if (response.url().includes("/facility-map/tiles/") && response.status() !== 200) errors.push(`tile ${response.status()} ${response.url()}`); });
  try {
    await page.goto(`${process.env.FACILITY_TEST_URL || "http://localhost:3003"}/tracking`, { waitUntil: "networkidle", timeout: 120000 });
    await page.locator(".facility-map-canvas .leaflet-interactive").first().waitFor({ timeout: 30000 });
    assert(await page.getByText("FICTIONAL DEMO", { exact: true }).count() === 1);
    assert(await page.getByText(/DEMO-DIGITIZED VECTOR/).count() === 1);
    assert.equal(await page.locator(".leaflet-tile-loaded").count(), 0, "Vector mode is not a raster background");
    await page.screenshot({ path: path.join(out, "01-vector-overview.png"), fullPage: true });

    const canvas = page.locator(".facility-map-canvas");
    const before = await canvas.screenshot();
    await page.getByRole("button", { name: "Zoom in" }).click();
    await page.waitForTimeout(850);
    assert(!before.equals(await canvas.screenshot()), "Zoom control must change the map");
    const zoomed = await canvas.screenshot();
    const box = await canvas.boundingBox();
    assert(box && box.width > 300 && box.height > 300);
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
    await page.mouse.wheel(0, -180);
    await page.waitForTimeout(800);
    assert(!zoomed.equals(await canvas.screenshot()), "Mouse wheel must zoom the map");
    const wheeled = await canvas.screenshot();
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .67, box.y + box.height * .63, { steps: 8 });
    await page.mouse.up();
    await page.waitForTimeout(500);
    assert(!wheeled.equals(await canvas.screenshot()), "Drag must pan the map");
    const panned = await canvas.screenshot();
    await canvas.dblclick({ position: { x: box.width * .52, y: box.height * .52 } });
    await page.waitForTimeout(700);
    assert(!panned.equals(await canvas.screenshot()), "Double-click must zoom the map");

    await page.getByRole("textbox", { name: "Search facility locations and assets" }).fill("DEMO-FLK-001");
    await page.getByRole("button", { name: /Demo search forklift/ }).first().click();
    assert(await page.getByRole("heading", { name: "Demo search forklift" }).count() === 1);
    assert(await page.getByText("47%", { exact: true }).count() === 1);
    assert(await page.getByText("1 fictional incident").count() === 1);
    await page.getByRole("button", { name: "Previous activity day" }).click();
    assert(await page.getByText("None recorded").count() === 1, "Activity date must filter the summary");
    await page.getByRole("button", { name: "Next activity day" }).click();
    assert(await page.getByText("1 fictional incident").count() === 1);
    await page.getByRole("button", { name: "Show blue route" }).click();
    assert(await page.getByText(/DEMO route follows connected, digitized corridors/).count() === 1);
    assert(await page.locator(".facility-active-route").count() === 1, "Blue route must be on the map");
    assert(await page.locator(".facility-active-route").getAttribute("d") !== null);
    assert(await page.getByText(/North Service Road|Central Access Road|West Access Loop|West Yard Loop/).count() > 0, "Road-by-road directions must appear");
    await page.waitForTimeout(850);
    await page.screenshot({ path: path.join(out, "02-search-and-blue-route.png"), fullPage: true });
    const firstRoute = await page.locator(".facility-active-route").getAttribute("d");
    await page.getByRole("combobox", { name: "Route destination" }).selectOption("DEMO-LOC-17");
    assert.notEqual(await page.locator(".facility-active-route").getAttribute("d"), firstRoute, "Changing destination must recalculate the blue route");
    await page.getByRole("combobox", { name: "Route destination" }).selectOption("DEMO-FLK-001");
    const dotBefore = await page.locator(".facility-navigation-dot").getAttribute("d");
    await page.getByRole("button", { name: "Start trip" }).click();
    await page.waitForTimeout(800);
    assert((await page.getByRole("progressbar", { name: "Simulated trip progress" }).getAttribute("aria-valuenow")) !== "0", "Trip must progress");
    assert.notEqual(await page.locator(".facility-navigation-dot").getAttribute("d"), dotBefore, "Navigation dot must move on the route");
    await page.getByRole("button", { name: "Pause trip" }).click();
    await page.screenshot({ path: path.join(out, "03-trip-in-progress.png"), fullPage: true });
    await page.locator(".facility-route-start").click();
    assert.equal(await page.getByRole("heading", { name: "East utility block" }).count(), 1, "Route start marker must open its location");
    await page.getByRole("button", { name: /Demo search forklift/ }).first().click();
    assert.equal(await page.getByRole("heading", { name: "Activity timeline" }).count(), 1, "Right panel includes activity history");
    await page.locator(".facility-detail-content").evaluate((element) => { element.scrollTop = element.scrollHeight; });
    await page.screenshot({ path: path.join(out, "07-activity-panel.png"), fullPage: true });

    await page.getByRole("textbox", { name: "Search facility locations and assets" }).fill("963-C410-GMS-301");
    await page.getByRole("button", { name: /963-C410-GMS-301/ }).first().click();
    assert(await page.getByText(/annotation box, not a verified/).count() === 1, "PDF codes must be searchable but unverified");
    await page.getByRole("textbox", { name: "Search facility locations and assets" }).fill("D1");
    assert(await page.getByRole("button", { name: /D1 industrial block/ }).count() >= 1, "Block search must work");
    await page.getByRole("textbox", { name: "Search facility locations and assets" }).fill("P-01");
    assert(await page.getByRole("button", { name: /Demo return area 01/ }).count() >= 1, "Parking search must work");
    await page.getByRole("button", { name: "Source drawing" }).click();
    await page.locator(".leaflet-tile-loaded").first().waitFor({ timeout: 30000 });
    assert(await page.getByText(/ORIGINAL ENGINEERING DRAWING/).count() === 1);
    await page.screenshot({ path: path.join(out, "04-source-drawing-comparison.png"), fullPage: true });
    await page.getByRole("button", { name: "Vector map" }).click();
    const mapWidthWithPanels = (await page.locator(".facility-map-area").boundingBox()).width;
    await page.getByRole("button", { name: "Collapse fleet list" }).click();
    assert.equal(await page.locator(".facility-list-panel").count(), 0, "Left panel must collapse");
    assert((await page.locator(".facility-map-area").boundingBox()).width > mapWidthWithPanels, "Map must expand when list collapses");
    await page.getByRole("button", { name: "Toggle fleet list" }).click();
    assert.equal(await page.locator(".facility-list-panel").count(), 1, "Left panel must reopen");
    await page.getByRole("button", { name: "Close details" }).click();
    assert.equal(await page.locator(".facility-detail-panel").count(), 0, "Right panel must close");
    await page.getByRole("button", { name: /Demo return area 01/ }).first().click();
    assert.equal(await page.locator(".facility-detail-panel").count(), 1, "Selection must reopen right panel");
    await page.getByRole("button", { name: "Fit", exact: true }).click();
    await page.waitForTimeout(700);
    const building = page.locator(".facility-building-sup-w");
    await building.click();
    assert(await page.getByRole("heading", { name: "West support offices" }).count() === 1, "Vector footprint must be clickable");

    await page.getByRole("combobox", { name: "Select demo scenario" }).selectOption("fuel");
    assert(await page.getByRole("heading", { name: "Demo low fuel generator" }).count() === 1);
    assert(await page.getByText("9%", { exact: true }).count() === 1);
    await page.getByRole("combobox", { name: "Select demo scenario" }).selectOption("movement");
    await page.waitForTimeout(3100);
    assert(await page.getByText(/Simulated clock: \+[12] min/).count() === 1, "Demo movement should advance");
    await page.locator(".facility-demo-bar label select").first().selectOption("5");
    await page.getByRole("combobox", { name: "Select demo scenario" }).selectOption("return");
    await page.waitForTimeout(3900);
    assert(await page.locator(".facility-detail-panel .facility-pill.returned").count() === 1, "Demo return should update status");
    await page.getByRole("button", { name: "Real records" }).click();
    assert(await page.getByText(/0 assets · 0 mapped/).count() === 1, "Real mode must not contain fictional markers");
    const unauthorized = await page.evaluate(async () => {
      const response = await fetch("/api/facility-map", { method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "place", code: "TEST", name: "Unauthorized", kind: "building", x: 100, y: 100 }) });
      return response.status;
    });
    assert.equal(unauthorized, 401, "Map writes require authentication");

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    mobile.on("pageerror", (error) => errors.push(error.message));
    await mobile.goto(`${process.env.FACILITY_TEST_URL || "http://localhost:3003"}/tracking`, { waitUntil: "networkidle", timeout: 120000 });
    await mobile.locator(".facility-map-canvas.leaflet-container").waitFor({ timeout: 30000 });
    await mobile.screenshot({ path: path.join(out, "05-mobile.png"), fullPage: true });
    await mobile.getByRole("button", { name: /Demo search forklift/ }).first().click();
    assert.equal(await mobile.locator(".facility-list-panel").count(), 0, "Mobile selection must reveal map and details");
    assert.equal(await mobile.locator(".facility-detail-panel").count(), 1, "Mobile details drawer must open");
    await mobile.screenshot({ path: path.join(out, "06-mobile-details.png"), fullPage: true });
    const horizontalOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
    assert(!horizontalOverflow, "No horizontal page overflow on mobile");
    assert.deepEqual(errors, []);
    console.log("Facility map browser check passed:", out);
    await mobile.close();
  } finally { await browser.close(); }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
